# Title:   JPT.SetSelectMethod()
# Desc:    Change the selection method in Jupiter to the specified one
# Version: 5.0.1
# Docs:    /docs/cli/5.0.1/psj-utility/PSJ-Utility_SetSelectMethod
# ---
# Select method to Body selection
JPT.SetSelectMethod(JPT.SelectMethodType.SELMTD_BODY)  # [hl]

# Select method to Face selection
JPT.SetSelectMethod(JPT.SelectMethodType.SELMTD_FACE)  # [hl]

# Select method to Edge selection
JPT.SetSelectMethod(JPT.SelectMethodType.SELMTD_EDGE)  # [hl]

# Select method to Node selection
JPT.SetSelectMethod(JPT.SelectMethodType.SELMTD_NODE)  # [hl]
